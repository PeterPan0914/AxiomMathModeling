def get_modeler_system_prompt(problem_analysis: str = "") -> str:
    """获取 ModelerAgent 的完整系统提示词（四阶段框架）。

    包含四阶段建模流程：
      阶段一：假设可行性审计
      阶段二：强制多方案对比（至少 3 个候选）
      阶段三：模型改进论证
      阶段四：双重输出（model_spec + model_narrative）

    Args:
        problem_analysis: 题目深度分析结果（来自 ProblemAnalystAgent），注入上下文。

    Returns:
        完整的系统提示词字符串。
    """
    sections = [
        _BASE_ROLE_AND_TASK,
        _PHASE1_ASSUMPTION_AUDIT,
        _PHASE2_COMPARISON,
        _PHASE3_IMPROVEMENT,
        _PHASE4_DUAL_OUTPUT,
        _METHOD_REFERENCE_TABLES,
        _QUALITY_REQUIREMENTS,
        _OUTPUT_RULES,
        _CHAIN_OF_THOUGHT,
    ]

    prompt = "\n".join(sections)

    if problem_analysis:
        prompt += f"\n\n---\n\n# 题目深度分析（来自 ProblemAnalystAgent，务必参考）\n\n{problem_analysis}\n"

    return prompt


def get_counterfactual_prompt(chosen_method: str, alternative_method: str) -> str:
    """获取反事实思维提示词，用于强制 ModelerAgent 考虑方法失败场景。

    在 ModelerAgent 选定方法后调用，生成 3 个可能让方法选择失败的场景。

    Args:
        chosen_method: 已选定的方法名称。
        alternative_method: 主要替代方案名称。

    Returns:
        反事实思维提示词字符串。
    """
    return f"""你已经选择了 **{chosen_method}**。

现在请扮演一个持不同意见的评审人，给出 3 个可能让这个方法选择失败的场景。不要敷衍——每个场景必须有具体的数据特征、失败机制和后果。

---

**场景一：数据结构不匹配**

如果数据中存在 {chosen_method} 无法处理的结构（例如：强空间相关性、非平稳突变、异方差性、层次嵌套等），会发生什么？
- 具体失败表现：...
- 对结果的影响：...
- 论文中的防御策略：如何在论文中提前说明你已考虑此风险？
- 检测手段：用什么统计检验或图表可以在代码中检测到这个问题？

**场景二：替代方案可能更优**

如果 {alternative_method} 实际上效果更好（例如：在交叉验证中 R² 高出 0.05 以上），你怎么论证你的选择仍然合理？
- {alternative_method} 在什么条件下可能胜出？
- 如果确实更优，你的备选方案是什么？
- 论文中如何措辞才能既诚实又有说服力？

**场景三：极端情况退化**

如果计算结果与直觉不符（例如：预测值为负数、优化结果违反物理约束、分类概率全为 0.5），你如何处理？
- {chosen_method} 在极端数据下的退化行为是什么？
- 代码中应该加入哪些防护性检查（sanity checks）？
- 如果发现退化，自动回退到什么方案？

---

**输出格式**：对每个场景，给出：
1. 触发条件（具体到数据特征）
2. 失败表现（具体到数值或图表）
3. 防御措施（具体到代码中的检查逻辑或论文中的措辞）
4. 严重程度（致命 / 重要 / 轻微）
"""


