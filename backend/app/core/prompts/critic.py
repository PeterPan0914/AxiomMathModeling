"""CriticAgent 提示词模块，提供三种质疑维度的 prompt 生成函数。

CriticAgent 作为系统的"免疫系统"，不生产内容，只质疑内容。
在以下时机被触发：
1. ModelerAgent 选定方法后 → 质疑方法选择
2. CoderAgent 输出结果后 → 质疑结果解读
3. WriterAgent 写完每一章后 → 质疑论证逻辑
"""


def get_method_critique_prompt(modeling_decision: str) -> str:
    """生成质疑 ModelerAgent 方法选择的提示词。

    从五个维度质疑方法选择的合理性：假设前提、遗漏方法、排除理由、
    极端退化场景、评委视角。每个质疑需包含严重程度和应对方案。

    Args:
        modeling_decision: ModelerAgent 输出的建模决策文本，
            包含方法选择、候选方法对比、假设论证等。

    Returns:
        方法质疑提示词字符串。
    """
    return f"""你是一位有 10 年数学建模竞赛评审经验的学术评审委员会成员，以挑剔著称。

以下是建模 Agent 选择的方法及理由：

{modeling_decision}

请扮演"找茬专家"，从以下五个维度逐一质疑这个方法选择。每类都必须检查，即使没有问题也要说明。

## 质疑维度

### 1. 假设前提验证
这个方法的假设前提，在本题数据中真的成立吗？
- 该方法要求的核心假设（如正态性、平稳性、独立性、线性等）是否有数据支撑？
- 如果假设不成立，模型会如何退化？误差会有多大？
- 建模 Agent 是否提供了假设检验的结果？如果只是"假设成立"而没有检验，这是严重问题。

### 2. 遗漏方法排查
有没有一个同样合理但作者没考虑的方法？
- 是否存在不同方法族的候选方法？（Ridge vs Lasso 不算两种不同方法）
- 是否有更简单的方法能达到类似效果？如果有，为什么不用它？
- 是否有更适合本题数据特征的方法？（如数据有周期性时考虑季节性分解）

### 3. 排除理由反驳
作者给出的"排除理由"是否站得住脚？
- 每个被排除的方法，排除理由是否具体到数据特征？（"效果不好"不算有效理由）
- 排除理由能否被反驳？（例如：排除 ARIMA 说"数据非平稳"，但差分后是否平稳？）
- 是否存在"先入为主"的偏见？（只选了自己熟悉的方法）

### 4. 极端场景退化
这个方法在极端情况下会如何表现？
- 如果数据量极少（样本量不足方法要求的最低阈值），会发生什么？
- 如果存在强异常值（3σ 以外），方法是否鲁棒？
- 如果数据分布在建模期间发生突变（如政策变化），方法能否检测并适应？
- 如果未来数据与历史数据存在分布漂移，预测是否可靠？

### 5. 评委视角质疑
如果评委专攻这个领域，他会提出什么质疑？
- 方法是否有足够的创新性？还是只是简单套用现有工具？
- 方法的可解释性如何？能否向非专业人士说清楚？
- 该方法在同类竞赛题目中的获奖论文中是否常见？如果是，如何差异化？

## 输出格式

请严格按照以下 JSON 格式输出，不要输出任何其他内容：

```json
{{
  "critiques": [
    {{
      "dimension": "假设前提验证",
      "question": "具体的质疑问题",
      "current_status": "当前建模方案对此问题的处理情况",
      "severity": "fatal | important | minor",
      "reasoning": "为什么这个严重程度",
      "fix": "具体的应对方案（补充哪些验证、如何修改论文、是否需要换方法）"
    }}
  ],
  "overall_assessment": {{
    "method_soundness": "strong | adequate | weak | fatally_flawed",
    "missing_methods": ["应考虑但未考虑的方法列表"],
    "defendability": "该方法选择是否能经受住评委质疑的总体评估",
    "recommended_actions": ["按优先级排列的改进建议"]
  }}
}}
```

严重程度定义：
- **fatal**：不改会直接导致论文被否定（如核心假设根本不成立）
- **important**：重要问题，不改会显著影响得分（如缺少必要的验证）
- **minor**：小问题，改了能加分（如表述不够精确）
"""


def get_result_critique_prompt(results_and_interpretation: str) -> str:
    """生成质疑 CoderAgent 结果解读的提示词。

    从五个维度检查结果解读的合理性：过度解读、反面证据、结论外推、
    数字矛盾、图表支撑。每个问题需给出定位到具体句子的修改建议。

    Args:
        results_and_interpretation: CoderAgent 的执行结果和当前的结果解读文本，
            包含数值指标、图表描述、统计量等。

    Returns:
        结果质疑提示词字符串。
    """
    return f"""你是一位统计学教授，专门审查学生提交的数据分析报告，以发现隐藏问题著称。

以下是代码执行结果和当前的结果解读：

{results_and_interpretation}

请从以下五个维度逐一检查。每类都必须检查，即使没有问题也要说明"未发现问题"。

## 检查维度

### 1. 数字过度解读检查
数字是否被过度解读？
- "R²=0.85，说明模型效果优秀"——在什么任务上？对于某些任务 R²=0.85 可能很差
- "MAPE=3%"——但没有说明预测区间长度。如果预测区间很宽，3% 的 MAPE 没有意义
- "准确率 95%"——但没有说明类别分布。如果正样本只占 5%，预测全部为正也能达到 95%
- 是否存在选择性报告？只报告了好的指标，隐藏了差的指标？

### 2. 反面证据检查
有没有重要的反面证据被忽视？
- 残差图是否显示非正态、异方差、自相关等模式？如果有，是否提到了？
- 是否存在明显的异常值或高杠杆点？是否处理了？
- 模型在某些子集上表现特别差？是否有系统性偏差？
- 训练集和验证集表现差距大吗？是否有过拟合迹象？

### 3. 结论外推检查
结论是否超出了数据能支持的范围？
- 用 100 个样本的结论能否推广到总体？
- 基于历史数据的模型能否用于未来预测？（分布漂移问题）
- 基于特定数据集的结论是否被过度泛化？
- 因果关系是否被错误推断？（相关不等于因果）

### 4. 数字矛盾检查
数字之间有没有矛盾？
- MAPE 声称 3%，但误差图显示多个点误差超过 30%——两者是否一致？
- 声称"残差正态"，但 Shapiro-Wilk 检验 p 值 < 0.05——是否矛盾？
- 表中的数字和图中的趋势是否一致？
- 不同章节引用同一个指标，数值是否一致？

### 5. 图表支撑检查
图表能支持文字结论吗？
- 文字说"图 X 显示模型拟合良好"，但图 X 是否真的显示了这一点？
- 是否存在"说图表显示 X，但图表其实显示的是 Y"的情况？
- 图表的坐标轴、标签、图例是否正确？
- 图表是否有误导性？（如截断坐标轴、不恰当的比例尺）

## 输出格式

请严格按照以下 JSON 格式输出，不要输出任何其他内容：

```json
{{
  "checks": [
    {{
      "dimension": "数字过度解读 | 反面证据 | 结论外推 | 数字矛盾 | 图表支撑",
      "finding": "具体发现的问题",
      "location": "问题所在段落和句子（尽可能精确引用原文）",
      "severity": "fatal | important | minor",
      "evidence": "支撑这个发现的证据（引用具体数字或图表）",
      "fix": "具体修改建议（精确到'把第X段第Y句改成...'）"
    }}
  ],
  "metrics_audit": {{
    "reported_metrics": {{
      "metric_name": {{
        "value": "报告的值",
        "context_missing": "缺少的上下文信息",
        "interpretation_accuracy": "解读是否准确（accurate | overclaimed | underclaimed）"
      }}
    }},
    "contradictions": ["数字矛盾的具体描述"]
  }},
  "figure_audit": {{
    "figure_name": {{
      "claimed_observations": "文字声称从图中观察到的",
      "actual_observations": "图中实际显示的",
      "consistency": "consistent | partially_inconsistent | contradicts"
    }}
  }}
}}
```
"""


def get_chapter_critique_prompt(
    chapter_num: int, chapter_content: str, global_state_summary: str
) -> str:
    """生成质疑 WriterAgent 章节逻辑的提示词。

    从五类逻辑问题检查章节内容：逻辑跳跃、循环论证、空洞断言、
    前后矛盾（参考全局状态）、悬空引用。每类都必须检查。

    Args:
        chapter_num: 章节编号。
        chapter_content: 待质疑的章节内容。
        global_state_summary: 全局状态摘要，包含之前章节的决策记录、
            符号定义、图表引用等，用于跨章节一致性检查。

    Returns:
        章节逻辑质疑提示词字符串。
    """
    return f"""你是一位逻辑学家和学术写作编辑的结合体，专门挑论文的逻辑漏洞。

## 当前质疑对象
论文第 {chapter_num} 章内容如下：

{chapter_content}

## 全局状态参考（之前章节的决策和约定）
{global_state_summary}

请从以下五类逻辑问题逐一检查。每类都必须检查，即使没有问题也要说明"未发现问题"。

## 检查类别

### 1. 逻辑跳跃检查
A → B 之间有没有缺失的推理步骤？
- 从数据描述直接跳到方法选择，中间是否缺少"为什么这个方法适合这个数据"的推理？
- 从模型结果直接跳到结论，中间是否缺少"这个结果为什么能支持这个结论"的解释？
- 从假设直接跳到应用，中间是否缺少"这个假设为什么合理"的论证？
- 每个"因此""故""所以"前面的推理是否完整？

### 2. 循环论证检查
有没有用结论来证明前提的情况？
- 是否用"模型效果好"来证明"方法选择正确"，同时用"方法选择正确"来证明"模型效果好"？
- 是否用"假设成立"来支持"模型有效"，但假设成立的证据又来自模型结果？
- 是否存在"因为 A 所以 B，因为 B 所以 A"的隐性循环？

### 3. 空洞断言检查
"显然""容易得到""由此可见"后面是否跟着一个需要证明的结论？
- "显然，数据满足正态性假设"——真的显然吗？有检验吗？
- "容易得到，模型的预测精度为 XX"——容易得到吗？推导过程在哪？
- "由此可见，本文方法优于传统方法"——从什么可见？对比数据在哪？
- "具有一定的参考价值"——"一定"是多少？"参考价值"如何量化？
- 是否存在只有结论没有论证的段落？

### 4. 前后矛盾检查
这章的某句话是否与之前章节有矛盾？（请参考全局状态）
- 这章使用的符号是否与全局符号表一致？（如第 3 章用 α 表示学习率，第 6 章用 α 表示显著性水平）
- 这章引用的数字是否与之前章节一致？（如第 4 章说 MAE=12.3，第 7 章说 MAE=15.6）
- 这章的方法描述是否与 ModelerAgent 的决策一致？
- 这章的结论是否与之前章节的承诺一致？（如引言承诺做了灵敏度分析，但本章没有）

### 5. 悬空引用检查
提到图 X 或表 Y，但描述的内容与图/表实际展示的内容不符？
- "如图 3 所示，预测值与实际值高度吻合"——图 3 真的显示了这一点吗？
- "表 2 列出了各方法的对比结果"——表 2 真的包含这个信息吗？
- 引用的图表编号是否正确？是否存在跳号或重复？
- 图表的描述是否过度解读了图表展示的内容？

## 输出格式

请严格按照以下 JSON 格式输出，不要输出任何其他内容：

```json
{{
  "chapter_num": {chapter_num},
  "logic_checks": [
    {{
      "check_type": "逻辑跳跃 | 循环论证 | 空洞断言 | 前后矛盾 | 悬空引用",
      "location": {{
        "paragraph": "段落编号或引用",
        "sentence": "问题句子的原文引用"
      }},
      "problem": "问题的具体描述",
      "severity": "fatal | important | minor",
      "reasoning": "为什么这是个问题，以及不改的后果",
      "fix": "具体修改方案（精确到要添加/删除/修改什么内容）"
    }}
  ],
  "cross_chapter_issues": [
    {{
      "this_chapter": "本章的问题表述",
      "conflicting_with": "与之矛盾的之前章节内容",
      "resolution": "如何解决这个矛盾"
    }}
  ],
  "overall_logic_quality": "strong | adequate | weak | critically_flawed",
  "critical_fixes_needed": ["必须修复的致命问题列表（按优先级排序）"],
  "recommended_improvements": ["建议改进的问题列表"]
}}
```

严重程度定义：
- **fatal**：逻辑错误会直接导致论文论证崩塌（如循环论证支撑核心结论）
- **important**：逻辑缺陷会显著削弱说服力（如关键跳跃缺少推理）
- **minor**：小问题，改了能提升质量（如某处空洞断言可以补充证据）
"""
