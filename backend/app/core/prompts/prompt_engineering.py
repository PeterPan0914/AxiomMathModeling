WRITER_COT_FRAMEWORK = """
---

# 强制推理链（Chain-of-Thought）—— 每个章节必须逐步完成

**你必须在撰写每个章节之前，按以下对应的推理链逐步思考。不允许模板化写作——每一句话都必须经过推理得出。**

## 摘要：四步推理法

撰写摘要前，必须按以下顺序思考并回答：

1. **问题张力**：这个问题为什么重要？不解决会怎样？解决它面临的核心矛盾是什么？（1 句话）
2. **方法选择理由**：为什么用这个方法而不是其他方法？一句话点明方法的核心优势与问题的匹配点。
3. **关键发现与解释**：得到了什么数值结果？这个结果意味着什么？（必须有具体数字，不能说"取得了较好效果"）
4. **现实启示**：这个结果对实际决策/工程/临床有什么指导意义？

**输出要求**：将以上四步推理结果压缩为 400-600 字的摘要，每个问题单独成段，每段必须包含具体数值。

## 问题分析：四步推理法

撰写每个问题的分析前，必须按以下顺序思考：

1. **数据结构观察**：数据长什么样？粒度是什么？样本量够不够？有没有特殊结构（如重复测量、层次结构）？
2. **难点识别**：这个问题比表面看起来难在哪里？哪些统计假设可能失效？
3. **候选方法对比**：列出 2-3 个候选方法，分析每个方法的假设条件在当前问题上是否成立。
4. **选择论证**：最终选择什么方法？用数据特征（而非泛泛而谈）论证为什么它最适合。

**输出要求**：将推理过程转化为流畅的论文段落（禁止分点列表），每段 200-300 字。

## 模型章节：五步推理法

撰写每个模型时，必须按以下顺序思考：

1. **数学建模**：写出完整的数学公式，每个符号必须定义。
2. **推导步骤**：展示从公式到解的关键推导步骤，不能跳步。
3. **求解过程**：使用什么算法/工具求解？参数如何设定？（必须有来源说明）
4. **结果解释与机理**：结果的数值含义是什么？背后的现实机理是什么？（不能只写"模型结果表明 X 与 Y 正相关"，要解释"为什么正相关"）
5. **局限性承认**：这个模型的假设哪些可能不成立？在什么情况下模型会失效？

**输出要求**：将推理过程转化为论文级段落，每个公式后必须有"其中"说明变量含义。禁止出现无来源的"默认值"参数。

## 敏感性分析：四步推理法

撰写敏感性分析前，必须按以下顺序思考：

1. **关键参数识别**：哪些参数对结果影响最大？为什么？（结合模型结构分析，而非随意选择）
2. **影响机理**：这个参数通过什么路径影响最终结果？是直接影响目标函数，还是通过约束条件间接影响？
3. **极端情形分析**：当参数取极端值时（如上下界），结果会怎样变化？是否会出现物理不可行的情况？
4. **现实含义**：参数敏感性对实际决策意味着什么？是应该更精确地估计这个参数，还是应该在决策中留出安全裕度？

**输出要求**：将推理过程转化为论文级段落，配合龙卷风图/蜘蛛图等可视化结果，用具体数值说明影响程度。
"""


def get_writer_cot_prompt() -> str:
    """获取 WriterAgent 的 Chain-of-Thought 强制推理链提示词。

    将返回值拼接到 WriterAgent 系统提示词末尾即可启用。

    Returns:
        CoT 推理链提示词字符串。
    """
    return WRITER_COT_FRAMEWORK


