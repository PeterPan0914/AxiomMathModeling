"""Prompt Engineering 模块，提供高级提示词工程技术。

本模块提供三类 CoT（Chain-of-Thought）框架，分别针对 ModelerAgent、WriterAgent、
CoderAgent 设计了强制性推理链，迫使 Agent 在给出结论前完成结构化深度思考。

每个 CoT 框架的函数返回一段可直接拼接到对应 Agent 系统提示词末尾的文本。
"""

# =============================================================================
# ModelerAgent 强制推理链
# =============================================================================

MODELER_COT_FRAMEWORK = """
---

# 强制推理链（Chain-of-Thought）—— 每个问题必须逐步完成

**你必须在给出建模方案之前，按以下五个阶段逐步思考并在输出中体现每一步的推理过程。不允许跳过任何阶段。**

## 阶段一：数据结构发现

在选择任何模型之前，你必须先回答以下问题：

1. **粒度与层级**：数据的每一行代表什么？是单次观测、单个个体、还是某个时间点的快照？是否存在嵌套结构（如同一个人有多条记录）？
2. **重复测量识别**：同一实体是否被多次测量？如果是，这意味着数据点之间不独立，必须考虑层次结构。
3. **样本量 vs 特征数**：有多少行？多少列？p/n 比率是多少？如果特征数接近或超过样本数，普通回归会过拟合。
4. **变量类型**：哪些是连续变量？哪些是分类变量？哪些是时序变量？有没有截断/删失数据？
5. **数据生成机制**：这些数据在现实中是怎么产生的？是实验采集、问卷调查、传感器记录、还是行政登记？生成过程会引入什么偏差？

**输出要求**：在方案开头用一小段文字明确写出以上发现，例如："数据共 N 行 M 列，每行代表一次检测，同一孕妇有多次检测记录（共 P 位孕妇），构成嵌套层次结构。p/n 比率约为 X/Y，样本量（充足/偏小/过小）。"

## 阶段二：难点识别

在理解数据结构后，识别本问题的核心难点：

1. **什么让这个问题比表面看起来更难？** 列出 2-3 个具体的技术挑战（如：数据不平衡、多重共线性、缺失值非随机、存在删失、非线性关系等）。
2. **哪些假设容易失效？** 列出你打算依赖的统计假设（如正态性、独立性、同方差性），并评估它们在当前数据上是否可能成立。
3. **如果不成立会怎样？** 对每个可能失效的假设，说明其后果以及你准备如何检验/补救。

**输出要求**：明确列出难点和假设风险，不要一笔带过。

## 阶段三：方法选择与论证（关键！）

你不能直接给出一个方法，你必须完成以下推理：

1. **列出至少 2-3 个候选方法**：针对本问题，至少考虑 2-3 种不同思路。
2. **逐一分析每个候选方法**：
   - 该方法的核心假设是什么？（如：线性回归假设线性关系和独立误差；混合效应模型允许组内相关；XGBoost 不需要线性假设但不提供置信区间）
   - 该方法在当前数据上假设是否成立？（结合阶段一和阶段二的发现）
   - 该方法的优势和劣势分别是什么？
3. **做出选择并给出理由**：最终选择哪个方法，为什么它比其他方法更适合当前问题。理由必须具体到数据特征（如："因为数据存在重复测量，普通回归违反独立性假设，所以选择混合效应模型"），而不是泛泛而谈（如："该方法效果更好"）。

**输出要求**：在方案中用明确的对比段落展示选择推理过程，评委会重点审查这一步。

## 阶段四：机理分析

模型不是凭空建立的——必须解释统计关系背后的现实机理：

1. **因果路径推测**：自变量为什么会影响因变量？在现实中，是什么物理/生物/社会/经济过程导致了这种关系？
2. **方向与量级**：关系是正向还是负向？为什么？关系的量级是否合理？（如：系数为 0.5 是否符合领域常识？）
3. **中介与混杂**：有没有可能存在中介变量（A 通过 B 影响 C）或混杂变量（C 同时影响 A 和 B）？如何处理？

**输出要求**：用 2-3 句话描述机理，不要只说"X 与 Y 相关"，要说明"为什么"。

## 阶段五：验证计划

在提出方案时，你必须同时设计验证方案：

1. **诊断检验**：列出至少 3 项具体诊断检验（如：残差正态性检验、VIF 多重共线性检验、随机效应必要性检验、ICC 组内相关系数等），说明每项检验的目的。
2. **验证指标**：选择哪些指标来衡量模型质量？为什么选这些指标而不是其他指标？（如：R² 用于衡量解释力，RMSE 用于衡量预测精度，AIC/BIC 用于模型比较）
3. **基线对比**：你将与什么基线模型对比？为什么？（如：简单线性回归作为基线，如果复杂模型没有显著优于基线，则不应使用复杂模型）
4. **失败预案**：如果验证不通过，你的 Plan B 是什么？

**输出要求**：在方案末尾用明确的小节列出验证计划。
"""


def get_modeler_cot_prompt() -> str:
    """获取 ModelerAgent 的 Chain-of-Thought 强制推理链提示词。

    将返回值拼接到 MODELER_PROMPT 末尾即可启用。

    Returns:
        CoT 推理链提示词字符串。
    """
    return MODELER_COT_FRAMEWORK


